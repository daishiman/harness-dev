/** id の重複と find の取り違えを起動時に止める (説明文の正本が二重になるのを防ぐ) */
{
  const ids = GLOSSARY.map((t) => t.id);
  const dup = ids.find((x, i) => ids.indexOf(x) !== i);
  if (dup) throw new Error(`glossary.mjs: id が重複しています (${dup})`);
}

/** 本文の照合に使う1本の正規表現 (GLOSSARY の並び順で先に書いたものが勝つ) */
