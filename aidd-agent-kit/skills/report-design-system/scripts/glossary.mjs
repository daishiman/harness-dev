/**
 * マーク回数を数え直すまとまりの先頭。ここから先は、同じ用語でもまた1回だけ印が付く。
 * 統計の要約カード・解釈・仮説は、読み手が「ここから別の話」と受け取る切れ目なので、それぞれに入口を置く。
 */
const BLOCK_START = /^<[^>]*class="(?:stats card|statement )/;

/** 用語マーク1つ分の HTML。text = 本文に出ていた書き方をそのまま残す (言い換えない) */
const termMark = (term, text) =>
  `<a class="term" href="#${term.id}" data-term="${esc(term.label)}">${text}<span class="term-q" aria-hidden="true">?</span></a>`;

/**
 * 同じ用語に何度も ? を付けるとかえって読みにくいので、マークを出す回数を絞る。
 *
 * 決めた密度: 「1つのまとまりにつき同じ用語1回だけ」(まとまりの切れ目は BLOCK_START)。
 * セクションごとに1回だけにすると、要因セクションは 統計の要約 → 解釈 → 仮説 と縦に長いので、
 * 下の方に出てくる用語に印が無く、読み手が上へ戻ることになる。逆に毎回付けると ? だらけで本文が読めない。
 * 読み手が視線を移す単位 (カード・文) ごとに1回なら、どこを読んでいても手元に説明への入口がある。
 *
 * @param {{id: string}} term マークしようとしている用語
 * @param {Set<string>} seen このまとまりで既にマークした用語 id
 * @returns {boolean} マークを付けるなら true
 */
export function markPolicy(term, seen) {
  return !seen.has(term.id);
}

/**
 * HTML の本文 (タグの外にある文字) から専門用語を見つけ、用語集へのリンク (.term) で包む。
 * 包まないところ: <svg> の中 (図の文字は別に data-tip がある)、属性値、見出し (h1〜h3)、
 * 目次、初心者向け概要 (.overview。ここは専門用語を使わない約束)。
 * @param {string} body セクションを並べた本文の HTML
 * @returns {{html: string, used: {id: string, label: string, what: string, how: string}[]}} used は出てきた順の用語
 */
export function markTerms(body) {
  const used = new Map();
  let seen = new Set();
  const markText = (text) =>
    text.replace(TERM_RE, (hit) => {
      const term = termOf(hit);
      if (!term || !markPolicy(term, seen)) return hit;
      seen.add(term.id);
      used.set(term.id, term);
      return termMark(term, hit);
    });

  // セクションと、その中の読み手が視線を移すまとまり (統計の要約カード / 解釈 / 仮説) ごとに数え直す。
  // 素通しにするまとまり: <svg> (図の文字は data-tip が担う)、見出し、初心者向け概要 (専門用語を使わない約束)、
  // 既存のリンク (要因ランキング・CTA・根拠ボタン。<a> の中に <a> を入れない)。残りをタグと文字に切り分ける
  const TOKEN = /<svg\b[\s\S]*?<\/svg>|<h[123]\b[\s\S]*?<\/h[123]>|<div class="overview card">[\s\S]*?<\/ul>\s*<\/div>|<a\b[\s\S]*?<\/a>|<[^>]*>|[^<]+/g;
  const html = body.replace(/<section\b[^>]*>[\s\S]*?<\/section>/g, (section) => {
    seen = new Set();
    return section.replace(TOKEN, (token) => {
      if (!token.startsWith("<")) return markText(token);
      if (BLOCK_START.test(token)) seen = new Set();
      return token;
    });
  });
  return { html, used: [...used.values()] };
}

/**
 * 本文で実際に使われた用語だけの用語集。画面では折りたたみ (常時表示しない)、印刷時は report.js が開く。
 * 用語マークのポップアップはこの <dd> の文を読むので、説明文はここにしか無い。
 */
export function glossaryBlock(used) {
  if (!used.length) return "";
  const rows = used
    .map((t) => `<dt id="${t.id}">${esc(t.label)}</dt><dd><span class="gl-what">${esc(t.what)}</span><span class="gl-how">${esc(t.how)}</span></dd>`)
    .join("\n");
  return (
    `\n<aside class="glossary card card-pad">\n<details>\n` +
    `<summary>用語の説明（${used.length}件）</summary>\n` +
    `<p class="gl-lead">本文の点線の語にカーソルを合わせるか、押すと同じ説明が出ます。</p>\n` +
    `<dl class="gl-list">\n${rows}\n</dl>\n</details>\n</aside>\n`
  );
}
