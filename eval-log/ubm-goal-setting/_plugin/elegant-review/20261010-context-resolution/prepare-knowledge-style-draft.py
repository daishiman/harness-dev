def sentences(s):
    out=[];buf='';stack=[];pairs={'「':'」','『':'』','（':'）','(':')'}
    for c in s:
        if c in pairs:stack.append(pairs[c])
        elif stack and c==stack[-1]:stack.pop()
        if c=='。' and not stack:
            if buf.strip():out.append(buf.strip())
            buf=''
        else:buf+=c
    if buf.strip():out.append(buf.strip())
    return out
def outside(s):return re.sub(r'「[^」]*」|『[^』]*』|（[^）]*）','',s)
def finite(s):return bool(re.search(r'(る|す|く|ぐ|う|つ|む|ぶ|ぬ|い|ない|だ|である|できる)$',s))
def join(parts):
    out=[]
    for s in parts[:-1]:
        if s.endswith('である'):out.append(s[:-3]+'であり')
        elif s.endswith('だ'):out.append(s[:-1]+'であり')
        elif s.endswith('から'):out.append(s+'であり')
        elif finite(s):out.append(s+'し')
        else:out.append(s+'であり')
    last=parts[-1]
    if not finite(last):last+='である'
    return '、'.join(out+[last])+'。'
